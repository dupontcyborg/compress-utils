class Summary:
    """data[(machine, binding, cell, fmt, impl)] -> rows [[level, native, comp, dec, ratio]]."""

    def __init__(self):
        raw = json.loads((PUBLISHED / "summary.json").read_text())
        self.meta = json.loads((PUBLISHED / "meta.json").read_text())
        self.series = {}
        self.index = defaultdict(set)  # (machine, binding, cell, fmt) -> impls
        for k, rows in raw["data"].items():
            m, b, c, f, impl = k.split("/")
            self.series[(m, b, c, f, impl)] = rows
            self.index[(m, b, c, f)].add(impl)
        self.memory = {}
        for k, lv in raw["memory"].items():
            m, f, impl = k.split("/")
            self.memory[(m, f, impl)] = lv
        self.wasm_size = raw.get("wasm_size")
        self.machines = list(self.meta["machines"])

    def rows(self, m, b, c, f, impl):
        return self.series.get((m, b, c, f, impl), [])

    def impls(self, m, b, c, f):
        return sorted(self.index.get((m, b, c, f), ()), key=lambda i: (i != "compress-utils", i in VARIANTS, dname(b, i).lower()))

    def formats(self, m, b, c):
        return [f for f in FORMATS if self.index.get((m, b, c, f))]

    def cells(self, b):
        return [c for c, _, _ in CELLS if any((self.machines[0], b, c, f) in self.index for f in FORMATS)]


def curve(rows, metric):
    """Points (ratio, speed) for plotting: one per distinct native level, a single point for a
    library with no levels or flat ratios; sorted by ratio."""
    idx = 2 if metric == "c" else 3
    groups = defaultdict(list)
    for level, native, c, d, ratio in rows:
        v = rows_val = (c if metric == "c" else d)
        if v is None or not ratio:
            continue
        key = native if (level is not None and native is not None) else "flat"
        groups[key].append((ratio, v))
    pts = [(geomean([a for a, _ in g]), geomean([b for _, b in g])) for g in groups.values()]
    return sorted(pts)


def is_single(rows):
    return all(r[0] is None or r[1] is None for r in rows) or len({r[1] for r in rows}) <= 1


def nearest_ours(ours_rows, ratio, metric):
    """Ours level closest in ratio (ties broken toward level 6) with a value for the metric."""
    idx = 2 if metric == "c" else 3
    cand = [r for r in ours_rows if r[idx] and r[4]]
    if not cand:
        return None
    return min(cand, key=lambda r: (round(abs(math.log(r[4] / ratio)), 3), abs((r[0] or 6) - 6)))


def rel_pairs(S, m, b, c, f, impl, metric):
    """Per matched level (or one pair for a library without levels): (competitor/ours speed, competitor/ours ratio)."""
    idx = 2 if metric == "c" else 3
    ours = S.rows(m, b, c, f, "compress-utils")
    rows = S.rows(m, b, c, f, impl)
    if not ours or not rows:
        return []
    out = []
    if is_single(rows):
        pts = curve(rows, metric)
        if not pts:
            return []
        ratio, v = pts[0]
        o = nearest_ours(ours, ratio, metric)
        if o:
            out.append((v / o[idx], ratio / o[4], o[0]))
        return out
    obylevel = {r[0]: r for r in ours}
    for r in rows:
        o = obylevel.get(r[0])
        if o and r[idx] and o[idx]:
            out.append((r[idx] / o[idx], r[4] / o[4], r[0]))
    return out


def rel_summary(S, m, b, c, f, impl, metric):
    """Geometric mean over levels: (speed multiple, ratio multiple) or None."""
    p = rel_pairs(S, m, b, c, f, impl, metric)
    if not p:
        return None
    return geomean([x[0] for x in p]), geomean([x[1] for x in p])


def peers_at_level(S, m, b, c, f, level=6, metric="c"):
    """Non-variant competitors compared with ours at one level: (impl, multiple, ratio multiple)."""
    out = []
    for impl in S.impls(m, b, c, f):
        if impl == "compress-utils" or impl in VARIANTS:
            continue
        pairs = [p for p in rel_pairs(S, m, b, c, f, impl, metric) if p[2] == level or is_single(S.rows(m, b, c, f, impl))]
        if pairs:
            out.append((impl, pairs[0][0], pairs[0][1]))
    return out


def comparable(ratio_mult):
    return abs(ratio_mult - 1) <= RATIO_BAND


def best_peer(S, m, b, c, f, metric, level=6):
    """The fastest comparable peer: (impl, multiple) or None."""
    cands = [(i, x) for i, x, rr in peers_at_level(S, m, b, c, f, level, metric) if comparable(rr)]
    return max(cands, key=lambda t: t[1]) if cands else None


def scoreboard(S, m, b, c=HEAD_CELL, level=6):
    """Counts over (format, direction) cells against the fastest comparable peer."""
    ahead = tie = behind = 0
    n_peer = 0
    skipped = 0
    for f in S.formats(m, b, c):
        for metric in "cd":
            peers = peers_at_level(S, m, b, c, f, level, metric)
            if not peers:
                continue
            n_peer += 1
            bp = best_peer(S, m, b, c, f, metric, level)
            if bp is None:
                skipped += 1
                continue
            x = bp[1]
            if x > 1 + TIE:
                behind += 1
            elif x < 1 / (1 + TIE):
                ahead += 1
            else:
                tie += 1
    return {"ahead": ahead, "tie": tie, "behind": behind, "skipped": skipped, "cells": n_peer}


def binding_rel(S, m, b, c, f, metric):
    """Binding / C core, geometric mean over the levels both measured."""
    idx = 2 if metric == "c" else 3
    bo = {r[0]: r for r in S.rows(m, b, c, f, "compress-utils")}
    co = {r[0]: r for r in S.rows(m, "c", c, f, "compress-utils")}
    xs = [bo[l][idx] / co[l][idx] for l in bo if l in co and bo[l][idx] and co[l][idx]]
    return geomean(xs)


def binding_range(S, m, b, c=HEAD_CELL):
    out = {}
    for metric in "cd":
        vals = {f: binding_rel(S, m, b, c, f, metric) for f in S.formats(m, b, c)}
        vals = {f: v for f, v in vals.items() if v}
        out[metric] = vals
    return out


