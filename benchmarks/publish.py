def level_row(rows, level):
    for r in rows:
        if r[0] == level:
            return r
    return None


LEVELS_SHOWN = (1, 6, 10)


def detail_tables(S, m, b, c):
    """Main table (levelled libraries) and the table of libraries without levels, as markdown."""
    head = ["Format", "Library"]
    for l in LEVELS_SHOWN:
        head += [f"L{l} ratio", f"L{l} comp", f"L{l} dec"]
    rows, single_rows = [], []
    for f in S.formats(m, b, c):
        ours = S.rows(m, b, c, f, "compress-utils")
        for impl in S.impls(m, b, c, f):
            r_all = S.rows(m, b, c, f, impl)
            nm = dname(b, impl)
            if impl == "compress-utils":
                cells = []
                for l in LEVELS_SHOWN:
                    r = level_row(ours, l)
                    cells += ([f"{r[4]:.2f}", fmt_mbps(r[2]), fmt_mbps(r[3])] if r else ["-"] * 3)
                rows.append([f"**{f}**", "**compress-utils**"] + [f"**{x}**" if x != "-" else x for x in cells])
                continue
            if is_single(r_all):
                pts_c, pts_d = curve(r_all, "c"), curve(r_all, "d")
                ratio = (pts_c or pts_d)[0][0] if (pts_c or pts_d) else None
                if ratio is None:
                    continue
                o = nearest_ours(ours, ratio, "d") or nearest_ours(ours, ratio, "c")
                if not o:
                    continue
                cs = pts_c[0][1] if pts_c else None
                ds = pts_d[0][1] if pts_d else None
                single_rows.append([f, nm, f"{ratio:.2f}", fmt_mbps(cs), fmt_mbps(ds), f"L{o[0]}" if o[0] else "-",
                                    f"{o[4]:.2f}", fmt_mbps(o[2]), fmt_mbps(o[3]),
                                    fmt_x(cs / o[2] if cs and o[2] else None, 1 + TIE), fmt_x(ds / o[3] if ds and o[3] else None, 1 + TIE)])
                continue
            cells = []
            for l in LEVELS_SHOWN:
                r, o = level_row(r_all, l), level_row(ours, l)
                if not r or not o:
                    cells += ["-"] * 3
                    continue
                cm = f"{fmt_mbps(r[2])} ({fmt_x(r[2] / o[2] if r[2] and o[2] else None, 1 + TIE)})" if r[2] else "-"
                dm = f"{fmt_mbps(r[3])} ({fmt_x(r[3] / o[3] if r[3] and o[3] else None, 1 + TIE)})" if r[3] else "-"
                cells += [f"{r[4]:.2f}", cm, dm]
            if any(x != "-" for x in cells):
                rows.append([f, nm] + cells)
    main = md_table(head, rows, ["l", "l"] + ["r"] * 9)
    single = None
    if single_rows:
        sh = ["Format", "Library", "Ratio", "Comp", "Dec", "Ours at", "Ours ratio", "Ours comp", "Ours dec", "Comp x", "Dec x"]
        single = md_table(sh, single_rows, ["l", "l", "r", "r", "r", "l", "r", "r", "r", "r", "r"])
    return main, single


