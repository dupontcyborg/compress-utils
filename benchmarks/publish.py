SIZE_START, SIZE_END = "<!-- size:start -->", "<!-- size:end -->"


def size_block(S):
    ws = S.wasm_size
    rows = []
    for a in SIZE_ALGOS:
        g = ws["gzip_bytes"][a]
        rows.append([a] + [f"{g[k] / 1024:.1f}" if g.get(k) else "-" for k in ("compress", "decompress", "both")])
    return "\n".join([
        "### Bundle size", "",
        f"Gzipped size in KiB of each algorithm's `.wasm` module (`gzip -9`, measured on the build of {ws['built']}): the default import ships both directions, while the `/compress` and `/decompress` subpaths ship only one.", "",
        md_table(["Algorithm", "Compress only", "Decompress only", "Both"], rows, ["l", "r", "r", "r"]), "",
        f"Each algorithm is a separate module and unused code is tree-shaken, so a page pays only for the algorithms and directions it imports. How the modules were made smaller: [wasm-size.md]({BLOB}docs/wasm-size.md)."])


def apply_markers(text, start, end, block, path):
    if start not in text or end not in text:
        raise SystemExit(f"{path}: missing {start} / {end} markers")
    a = text.index(start) + len(start)
    return text[:a] + "\n" + block + "\n" + text[text.index(end):]


def apply_block(text, block, path):
    if MARK_START not in text or MARK_END not in text:
        raise SystemExit(f"{path}: missing {MARK_START} / {MARK_END} markers")
    a = text.index(MARK_START) + len(MARK_START)
    b = text.index(MARK_END)
    return text[:a] + "\n" + block + "\n" + text[b:]


def current_block(text):
    a = text.index(MARK_START) + len(MARK_START)
    b = text.index(MARK_END)
    return text[a:b]


