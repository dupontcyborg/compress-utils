def sig(x, n=4):
    return None if x is None else float(f"{x:.{n}g}")


def geomean(xs):
    xs = [x for x in xs if x and x > 0]
    return math.exp(sum(map(math.log, xs)) / len(xs)) if xs else None


def median(xs):
    xs = sorted(xs)
    if not xs:
        return None
    n = len(xs)
    return xs[n // 2] if n % 2 else (xs[n // 2 - 1] + xs[n // 2]) / 2


def fmt_mbps(v):
    if v is None:
        return "-"
    if v >= 100:
        return f"{v:.0f}"
    if v >= 10:
        return f"{v:.1f}"
    return f"{v:.2f}"


def fmt_x(v, bold_over=None):
    if v is None:
        return "-"
    s = f"{v:.2f}x"
    if bold_over is not None and v > bold_over:
        s = f"**{s}**"
    return s


def fmt_mib(kib):
    if kib is None:
        return "-"
    m = kib / 1024
    if m >= 10:
        return f"{m:.0f}"
    if m >= 0.995:
        return f"{m:.1f}"
    return f"{m:.2f}"


def md_table(header, rows, align=None):
    align = align or ["l"] * len(header)
    sep = ["---:" if a == "r" else ":---" for a in align]
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join(sep) + " |"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


