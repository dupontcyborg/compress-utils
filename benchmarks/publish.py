def panel_series(S, m, b, c, f, metric, include_variants, peers_only=None):
    out = []
    for impl in S.impls(m, b, c, f):
        if impl in VARIANTS and not include_variants:
            continue
        rows = S.rows(m, b, c, f, impl)
        pts = curve(rows, metric)
        if not pts:
            continue
        out.append({"impl": impl, "name": dname(b, impl), "ours": impl == "compress-utils",
                    "variant": impl in VARIANTS, "pts": pts})
    return out


def draw_panel(ax, th, series, title, xlabel=False):
    from matplotlib.ticker import FuncFormatter, LogLocator, MaxNLocator, NullLocator
    ax.set_facecolor(th["bg"])
    xs, ys = [], []
    for s in sorted(series, key=lambda s: (s["ours"], s["variant"] is False)):
        px, py = zip(*s["pts"])
        xs += px
        ys += py
        if s["ours"]:
            ax.plot(px, py, "-o", color=OURS_COLOR, lw=3.2, ms=5.0, zorder=4, solid_capstyle="round")
            continue
        col, mk = lib_style(s["name"].split(" (")[0] if s["variant"] else s["name"])
        ls = "--" if s["variant"] else "-"
        if len(px) == 1:
            ax.plot(px, py, mk, color=col, ms=7, mec=th["bg"], mew=0.6, zorder=6)
        else:
            ax.plot(px, py, ls + mk, color=col, lw=1.1, ms=3.4, zorder=6, alpha=0.95)
    ax.set_yscale("log")
    if xs:
        xmin, xmax = min(xs), max(xs)
        pad = max((xmax - xmin) * 0.06, xmax * 0.03)
        ax.set_xlim(xmin - pad, xmax + pad)
        ylo, yhi = min(ys) / 1.5, max(ys) * 1.6
        ax.set_ylim(ylo, yhi)
        decades = math.log10(yhi / ylo)
        if decades > 3:
            ax.yaxis.set_major_locator(LogLocator(base=10, subs=(1.0,)))
            ax.yaxis.set_minor_locator(NullLocator())
        elif decades > 1.3:
            ax.yaxis.set_major_locator(LogLocator(base=10, subs=(1.0, 2.0, 5.0)))
            ax.yaxis.set_minor_locator(NullLocator())
        else:
            ax.yaxis.set_major_locator(LogLocator(base=10, subs=(1.0, 2.0, 3.0, 5.0, 7.0)))
            ax.yaxis.set_minor_locator(NullLocator())
    ax.yaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v:g}"))
    ax.xaxis.set_major_locator(MaxNLocator(nbins=4))
    span = (max(xs) - min(xs)) if xs else 1
    dec = 2 if span < 0.5 else 1
    ax.xaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v:.{dec}f}" if abs(v) < 10 else f"{v:.0f}"))
    ax.grid(True, which="major", color=th["grid"], lw=0.6)
    ax.set_axisbelow(True)
    for sp in ax.spines.values():
        sp.set_color(th["spine"])
        sp.set_linewidth(0.7)
    ax.tick_params(colors=th["muted"], labelsize=6.5, length=2.5, width=0.6, pad=2)
    ax.set_title(title, fontsize=7.6, color=th["fg"], loc="left", pad=3)
    if xlabel:
        ax.set_xlabel("compression ratio", fontsize=6.8, color=th["muted"], labelpad=1.5)
    if not xs:
        ax.text(0.5, 0.5, "no data", transform=ax.transAxes, ha="center", va="center", color=th["muted"], fontsize=7)


