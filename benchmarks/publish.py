SIZE_ALGOS = ["zstd", "brotli", "zlib", "gzip", "xz", "lz4", "bz2", "snappy"]


def wasm_sizes(dist: Path):
    """gzip -9 bytes of each algorithm's .wasm per direction in a built bindings/wasm/dist (the method
    of benchmarks/size/js_size.py, which gzips the module at level 9). Keeps the previous numbers
    when there is no build to measure."""
    import gzip
    import datetime
    base = dist / "algorithms"
    if not (base / "zstd" / "zstd.wasm").exists():
        prev = PUBLISHED / "summary.json"
        if prev.exists():
            old = json.loads(prev.read_text()).get("wasm_size")
            if old:
                print("summarize: no WASM build to measure, keeping the previous sizes")
                return old
        return None
    out = {}
    for a in SIZE_ALGOS:
        out[a] = {}
        for key, sub in (("both", ""), ("compress", "compress"), ("decompress", "decompress")):
            f = base / a / sub / f"{a}.wasm" if sub else base / a / f"{a}.wasm"
            out[a][key] = len(gzip.compress(f.read_bytes(), 9)) if f.exists() else None
    built = datetime.datetime.fromtimestamp((base / "zstd" / "zstd.wasm").stat().st_mtime).strftime("%Y-%m-%d")
    return {"built": built, "gzip_bytes": out}


def dump_summary_top(summary: dict) -> str:
    """One line per series. data keys are machine/binding/cell/format/impl -> rows
    [level, native level, compress MB/s, decompress MB/s, ratio]; memory keys are
    machine/format/impl -> {level: [compress one-shot, stream, 4 KiB, decompress one-shot,
    stream, 4 KiB]} in KiB over the output."""
    sections = []
    for key in ("data", "memory"):
        parts = []
        for m, mv in summary[key].items():
            if key == "data":
                for b, bv in mv.items():
                    for c, cv in bv.items():
                        for f, fv in cv.items():
                            for impl, rows in fv.items():
                                parts.append((f"{m}/{b}/{c}/{f}/{impl}", rows))
            else:
                for f, fv in mv.items():
                    for impl, lv in fv.items():
                        parts.append((f"{m}/{f}/{impl}", lv))
        body = ",\n".join(f"    {json.dumps(k)}: {json.dumps(v, separators=(',', ':'))}" for k, v in parts)
        sections.append(f'  "{key}": {{\n{body}\n  }}')
    ws = summary.get("wasm_size")
    if ws:
        sections.append(f'  "wasm_size": {json.dumps(ws, separators=(",", ":"))}')
    return "{\n" + ",\n".join(sections) + "\n}\n"


