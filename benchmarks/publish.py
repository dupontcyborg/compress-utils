def versions_sentence(meta):
    v = meta["competitor_versions"]
    if v and isinstance(next(iter(v.values())), dict):
        v = v[next(iter(v))]
    keys = [k for k in v if "-" in k and k not in ("c-baseline",)]
    pairs = []
    for k in sorted(v):
        if k in ("c", "python", "go", "rust", "wasm", "c-baseline") or v[k] in ("vendored", "baseline"):
            continue
        name = k.split("-", 1)[1] if "-" in k else k
        pairs.append(f"{name} {v[k]}")
    own = v.get("c", "?")
    return f"compress-utils {own}. Competitor versions as recorded in the results: " + ", ".join(pairs) + "."


