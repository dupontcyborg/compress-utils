def cmd_summarize(args):
    if not args.runs:
        sys.exit("summarize: --runs name=dir [name=dir ...] is required")
    data, memory = {}, {}
    versions: dict[str, dict] = {}
    machines_meta, sha_set, dirty_set, stamps = {}, set(), set(), []
    samples = {}
    input_bytes = {}
    dropped = 0
    for spec in args.runs:
        name, _, d = spec.partition("=")
        if not d or not os.path.isdir(d):
            sys.exit(f"summarize: bad --runs entry {spec!r} (want name=directory)")
        eco = sorted(glob.glob(os.path.join(d, "*ecosystem*.json")))
        mem = sorted(glob.glob(os.path.join(d, "*memory*.json")))
        if not eco:
            sys.exit(f"summarize: no *ecosystem*.json in {d}")
        mdata = data.setdefault(name, {})
        versions[name] = {}
        for f in eco:
            doc = json.load(open(f))
            meta = doc["meta"]
            sha_set.add(meta["git_sha"])
            dirty_set.add(bool(meta.get("git_dirty")))
            stamps.append(meta["timestamp"])
            machines_meta[name] = meta["machine"]
            samples.setdefault(meta.get("corpus", "?"), meta["samples"])
            for drv in meta["drivers"]:
                versions[name][drv["key"]] = drv["version"]
            for r in doc["records"]:
                if not r.get("verified"):
                    dropped += 1
                    continue
                input_bytes.setdefault(r["input_id"], r["input_bytes"])
                series = (mdata.setdefault(binding_of(r), {}).setdefault(cell_of(r), {})
                          .setdefault(r["algo"], {}).setdefault(r["impl"], []))
                series.append(_row(r))
        for rows_by_cell in mdata.values():
            for fm in rows_by_cell.values():
                for impls in fm.values():
                    for impl, rows in impls.items():
                        rows.sort(key=lambda x: (x[0] is None, x[0] or 0))
        mm = memory.setdefault(name, {})
        for f in mem:
            doc = json.load(open(f))
            sha_set.add(doc["meta"]["git_sha"])
            for r in doc["records"]:
                if not r.get("verified"):
                    dropped += 1
                    continue
                slot = {("mem", "dickens"): (0, 3), ("memstream", "dickens"): (1, 4), ("mem", "dickens.first4k"): (2, 5)}[
                    (r["mode"], r["input_id"])]
                cell = (mm.setdefault(r["algo"], {}).setdefault(r["impl"], {})
                        .setdefault(str(r["level"]), [None] * 6))
                cell[slot[0]] = r["mem_compress_overhead_kb"]
                cell[slot[1]] = r["mem_decompress_overhead_kb"]
    names = list(data)
    same = all(versions[n] == versions[names[0]] for n in names)
    meta_out = {
        "date": min(stamps)[:10],
        "commit": sorted(sha_set)[0],
        "commit_label": sorted(sha_set)[0] + (" plus driver fixes" if any(dirty_set) else ""),
        "all_stages_same_commit": len(sha_set) == 1,
        "machines": {n: {**MACHINES.get(n, {"short": n, "long": n}),
                         "os": f"{machines_meta[n]['os']} {machines_meta[n]['os_release']}",
                         "arch": machines_meta[n]["arch"], "cpu": machines_meta[n]["cpu"]} for n in names},
        "competitor_versions": versions[names[0]] if same else versions,
        "input_bytes": input_bytes,
        "samples_by_tier": samples,
        "policy": POLICY,
    }
    summary = {"data": data, "memory": memory, "wasm_size": wasm_sizes(Path(args.wasm_dist) if args.wasm_dist else DEFAULT_WASM_DIST)}
    PUBLISHED.mkdir(parents=True, exist_ok=True)
    text = dump_summary_top(summary)
    (PUBLISHED / "summary.json").write_text(text)
    (PUBLISHED / "meta.json").write_text(json.dumps(meta_out, indent=2, sort_keys=True) + "\n")
    n = sum(len(rows) for m in data.values() for b in m.values() for c in b.values() for f in c.values() for rows in f.values())
    print(f"summarize: {n} rows, {len(text) / 1e6:.2f} MB summary.json ({dropped} unverified records dropped)")


