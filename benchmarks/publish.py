def save_png(fig, path: Path, dpi: int, limit=350_000):
    """Write the PNG, quantizing to a palette if the full-colour file is over the size budget."""
    import io
    from PIL import Image
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=dpi, facecolor=fig.get_facecolor(), metadata={"Software": None})
    data = buf.getvalue()
    if len(data) > limit:
        im = Image.open(io.BytesIO(data)).convert("RGB")
        q = im.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        b2 = io.BytesIO()
        q.save(b2, format="PNG", optimize=True)
        data = b2.getvalue()
    path.write_bytes(data)
    return len(data)


