def cmd_render(args, check=False):
    S = Summary()
    plan = chart_plan(S)
    pages = build_pages(S)
    blocks = {p: readme_block(S, p, plan) for p in README_TARGETS}
    size = size_block(S) if S.wasm_size else None
    WASM_README = "bindings/wasm/README.md"
    expected_imgs = [f"{sp['name']}-{t}.png" for sp in plan for t in themes_of(sp)]
    if check:
        bad = []
        for name, text in pages.items():
            f = DOCS / name
            if not f.exists() or f.read_text() != text:
                bad.append(f"docs/benchmarks/{name} differs or is missing")
        for p, blk in blocks.items():
            f = REPO / p
            if not f.exists() or MARK_START not in f.read_text():
                bad.append(f"{p}: markers missing")
            elif current_block(f.read_text()) != "\n" + blk + "\n":
                bad.append(f"{p}: bench block differs")
        if size:
            f = REPO / WASM_README
            txt = f.read_text()
            if SIZE_START not in txt or SIZE_END not in txt:
                bad.append(f"{WASM_README}: size markers missing")
            elif txt[txt.index(SIZE_START) + len(SIZE_START):txt.index(SIZE_END)] != "\n" + size + "\n":
                bad.append(f"{WASM_README}: size block differs")
        missing = [n for n in expected_imgs if not (DOCS / "img" / n).exists()]
        if missing:
            bad.append(f"{len(missing)} PNGs missing in docs/benchmarks/img: {', '.join(missing[:5])}")
        print(f"check: {len(expected_imgs) - len(missing)}/{len(expected_imgs)} PNGs present (contents not compared)")
        if bad:
            print("check: FAILED\n  " + "\n  ".join(bad))
            sys.exit(1)
        print("check: pages and README blocks match")
        return
    DOCS.mkdir(parents=True, exist_ok=True)
    if not args.no_charts:
        sizes = render_charts(S, DOCS / "img", args.only)
        for n, s in sizes:
            print(f"  {n}: {s / 1000:.0f} KB")
    for name, text in pages.items():
        (DOCS / name).write_text(text)
    for p, blk in blocks.items():
        f = REPO / p
        f.write_text(apply_block(f.read_text(), blk, p))
    if size:
        f = REPO / WASM_README
        f.write_text(apply_markers(f.read_text(), SIZE_START, SIZE_END, size, WASM_README))
    print(f"render: {len(pages)} pages, {len(blocks)} README blocks, {len(expected_imgs)} images")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="re-render pages and README blocks in memory and fail if the committed ones differ (PNGs: presence only)")
    sub = ap.add_subparsers(dest="cmd")
    s = sub.add_parser("summarize", help="run directories -> benchmarks/published/summary.json and meta.json (stdlib only)")
    s.add_argument("--runs", nargs="+", metavar="NAME=DIR", help="machine name and run directory, e.g. c8g=benchmarks/results/ec2/run3/c8g")
    s.add_argument("--wasm-dist", metavar="DIR", help="built bindings/wasm/dist to measure module sizes from (default: bindings/wasm/dist; the previous sizes are kept if it is missing)")
    r = sub.add_parser("render", help="summary -> PNGs, markdown pages, README blocks (matplotlib for the PNGs)")
    r.add_argument("--check", action="store_true", dest="check_sub", help="same as the top-level --check")
    r.add_argument("--no-charts", action="store_true", help="skip PNG rendering")
    r.add_argument("--only", metavar="REGEX", help="render only charts whose name matches")
    a = sub.add_parser("all", help="summarize, then render")
    a.add_argument("--runs", nargs="+", metavar="NAME=DIR")
    a.add_argument("--wasm-dist", metavar="DIR")
    a.add_argument("--no-charts", action="store_true")
    a.add_argument("--only", metavar="REGEX")
    args = ap.parse_args(argv)
    if args.check or getattr(args, "check_sub", False):
        return cmd_render(args, check=True)
    if args.cmd == "summarize":
        return cmd_summarize(args)
    if args.cmd == "render":
        return cmd_render(args)
    if args.cmd == "all":
        cmd_summarize(args)
        return cmd_render(args)
    ap.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
