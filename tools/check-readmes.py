#!/usr/bin/env python3
"""Keep the root and per-binding READMEs aligned with each other and with the source of truth.

The algorithm and language tables are generated from docs/readme/manifest.json
into marked regions of each README:

    <!-- BEGIN:algorithms -->
    ...generated...
    <!-- END:algorithms -->

Everything else in a README is hand-written, but is checked against the repo:

  * generated regions match the manifest (`--fix` rewrites them)
  * the manifest's algorithm list matches the cu_algorithm_t enum in include/compress_utils.h
  * version literals in examples match CMakeLists.txt's DEFAULT_VERSION
  * "eight algorithms", "seven upstream libraries" and the shields.io count badges match the manifest
    and codec-versions.json
  * required sections are present and in the order docs/readme-skeleton.md prescribes
  * prose is not hard-wrapped
  * relative links resolve (and registry-published READMEs use absolute links)
  * no rustdoc-hidden `# ` lines leak into a README code fence
  * license and repository metadata agree across Cargo.toml, pyproject.toml and package.json

Usage:
    tools/check-readmes.py          # CI mode: print problems, exit 1 if any
    tools/check-readmes.py --fix    # regenerate the marked regions, then check
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
MANIFEST = REPO_ROOT / "docs" / "readme" / "manifest.json"
HEADER = REPO_ROOT / "include" / "compress_utils.h"
CMAKELISTS = REPO_ROOT / "CMakeLists.txt"
CODEC_VERSIONS = REPO_ROOT / "codec-versions.json"
REPO_URL = "https://github.com/dupontcyborg/compress-utils"

NUMBER_WORDS = {
    "one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7,
    "eight": 8, "nine": 9, "ten": 10, "eleven": 11, "twelve": 12, "thirteen": 13,
}

# Required sections, in order, for each README kind. (canonical name, heading regex).
# A heading of any level matches; extra sections may appear anywhere between them.
BINDING_SECTIONS = [
    ("Installation", r"^install"),
    ("Quick start", r"^quick start"),
    ("Streaming", r"streaming"),
    ("Supported algorithms", r"^(supported )?algorithms"),
    ("Raw blocks and output capacity", r"^raw blocks"),
    ("Compression levels", r"levels"),
    ("Errors and limits", r"^errors?\b"),
    ("Concurrency", r"concurrency|thread"),
    ("License", r"^license"),
]
ROOT_SECTIONS = [
    ("Supported languages", r"^supported languages"),
    ("Supported algorithms", r"^supported algorithms"),
    ("Benchmarks", r"^benchmarks"),
    ("Building from source", r"^building from source"),
    ("License", r"^license"),
]

# READMEs rendered on a registry that does not resolve repo-relative links.
ABSOLUTE_LINKS_ONLY = {"python", "wasm"}

SPELLING_HEADER = {
    "cpp": "Enum", "go": "Constant", "python": "Spelling", "rust": "Variant", "wasm": "Subpath",
}

REGION_RE = re.compile(r"^<!-- BEGIN:(\w+)\b.*?-->\s*$")
END_RE = re.compile(r"^<!-- END:(\w+)\s*-->\s*$")
GENERATED_NOTE = (
    "<!-- Generated by tools/check-readmes.py from docs/readme/manifest.json. "
    "Edit the manifest and run `tools/check-readmes.py --fix`, not this block. -->"
)


# --------------------------------------------------------------------------- #
# Loading the sources of truth
# --------------------------------------------------------------------------- #


def load_manifest() -> dict:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def core_version() -> str:
    m = re.search(r'set\(DEFAULT_VERSION\s+"([^"]+)"\)', CMAKELISTS.read_text(encoding="utf-8"))
    if not m:
        sys.exit("error: could not find DEFAULT_VERSION in CMakeLists.txt")
    return m.group(1)


def upstream_library_count() -> int:
    data = json.loads(CODEC_VERSIONS.read_text(encoding="utf-8"))
    return sum(1 for k in data if not k.startswith("_"))


# --------------------------------------------------------------------------- #
# Table rendering
# --------------------------------------------------------------------------- #


def table(headers: list[str], rows: list[list[str]]) -> list[str]:
    widths = [max(len(h), *(len(r[i]) for r in rows)) for i, h in enumerate(headers)]

    def line(cells: list[str]) -> str:
        return "| " + " | ".join(c.ljust(w) for c, w in zip(cells, widths)) + " |"

    return [line(headers), "|" + "|".join("-" * (w + 2) for w in widths) + "|"] + [line(r) for r in rows]


def code_spelling(spelling: str) -> str:
    """`"bz2" (also "bzip2")` → `` `"bz2"` (also "bzip2") ``: code-format only the leading token."""
    m = re.match(r"^(.*?)( \(.*\))?$", spelling)
    return f"`{m.group(1)}`{m.group(2) or ''}"


def render_algorithms(manifest: dict, key: str) -> list[str]:
    algos = manifest["algorithms"]
    if key == "root":
        core = [a for a in algos if a["kind"] == "core"]
        raw = [a for a in algos if a["kind"] == "raw"]
        out = table(
            ["Algorithm", "Strength", "Wire format produced"],
            [[f"[{a['name']}]({a['url']})", a["strength"], a["wire"]] for a in core],
        )
        out += ["", "Raw block formats, for reading data from other tools:", ""]
        out += table(
            ["Format", "Wire format"],
            [[f"[{a['name']}]({a['url']})", a["wire"]] for a in raw],
        )
        return out
    if key == "c":
        return []
    return table(
        ["Algorithm", SPELLING_HEADER[key], "Wire format"],
        [[a["name"], code_spelling(a["spelling"][key]), a["wire"]] for a in algos],
    )


def render_languages(manifest: dict) -> list[str]:
    rows = [
        [f"**{l['name']}**", l["install"], f"[{l['docs_label']}]({l['docs']})"]
        for l in manifest["languages"]
    ]
    planned = manifest.get("planned_languages")
    if planned:
        rows.append([", ".join(planned), "_Planned_", ""])
    return table(["Language", "Install", "Docs"], rows)


def render_region(manifest: dict, readme_key: str, region: str) -> list[str] | None:
    if region == "algorithms":
        body = render_algorithms(manifest, readme_key)
    elif region == "languages" and readme_key == "root":
        body = render_languages(manifest)
    else:
        return None
    return [GENERATED_NOTE, ""] + body


# --------------------------------------------------------------------------- #
# Markdown scanning helpers
# --------------------------------------------------------------------------- #


def iter_lines(lines: list[str]):
    """Yield (index, line, in_fence, fence_lang): in_fence is True on the fence lines too."""
    fence = None
    for i, line in enumerate(lines):
        stripped = line.lstrip()
        if fence is None and (stripped.startswith("```") or stripped.startswith("~~~")):
            fence = stripped[:3]
            yield i, line, True, stripped[3:].strip().split()[0] if stripped[3:].strip() else ""
            continue
        if fence is not None:
            yield i, line, True, ""
            if stripped.startswith(fence):
                fence = None
            continue
        yield i, line, False, ""


def slugify(heading: str) -> str:
    s = re.sub(r"[`*_~]", "", heading.strip().lower())
    s = re.sub(r"[^\w\- ]", "", s)
    return s.replace(" ", "-")


def headings(lines: list[str]) -> list[tuple[int, int, str]]:
    """(line index, level, text) for every ATX heading outside a code fence."""
    out = []
    for i, line, in_fence, _ in iter_lines(lines):
        if in_fence:
            continue
        m = re.match(r"^(#{1,6})\s+(.*?)\s*#*\s*$", line)
        if m:
            out.append((i, len(m.group(1)), m.group(2)))
    return out


# --------------------------------------------------------------------------- #
# Region regeneration
# --------------------------------------------------------------------------- #


def process_regions(manifest: dict, key: str, lines: list[str], fix: bool, problems: list[str], rel: str):
    """Compare (or rewrite) each marked region. Returns the possibly-updated lines."""
    out: list[str] = []
    seen: set[str] = set()
    i = 0
    while i < len(lines):
        m = REGION_RE.match(lines[i])
        if not m:
            out.append(lines[i])
            i += 1
            continue
        name = m.group(1)
        end = next((j for j in range(i + 1, len(lines)) if END_RE.match(lines[j])), None)
        if end is None:
            problems.append(f"{rel}:{i + 1}: BEGIN:{name} has no matching END:{name}")
            out.extend(lines[i:])
            return out
        seen.add(name)
        expected = render_region(manifest, key, name)
        if expected is None:
            problems.append(f"{rel}:{i + 1}: unknown generated region '{name}' for this README")
            out.extend(lines[i:end + 1])
        else:
            current = lines[i + 1:end]
            if current != expected:
                problems.append(f"{rel}:{i + 1}: region '{name}' is out of date with docs/readme/manifest.json (run --fix)")
            out.append(lines[i])
            out.extend(expected if fix else current)
            out.append(lines[end])
        i = end + 1
    required = {"root": {"algorithms", "languages"}, "c": set()}.get(key, {"algorithms"})
    for name in sorted(required - seen):
        problems.append(f"{rel}: missing <!-- BEGIN:{name} --> / <!-- END:{name} --> region")
    return out


# --------------------------------------------------------------------------- #
# Individual checks
# --------------------------------------------------------------------------- #


def check_enum(manifest: dict, problems: list[str]) -> None:
    text = HEADER.read_text(encoding="utf-8")
    enum_ids = re.findall(r"CU_ALGO_(\w+)\s*=", text)
    aliases = set(manifest.get("aliases", []))
    enum_ids = [e for e in enum_ids if e not in aliases]
    manifest_ids = [a["id"] for a in manifest["algorithms"]]
    if set(enum_ids) != set(manifest_ids):
        missing = sorted(set(enum_ids) - set(manifest_ids))
        extra = sorted(set(manifest_ids) - set(enum_ids))
        problems.append(
            f"docs/readme/manifest.json: algorithms differ from cu_algorithm_t in include/compress_utils.h "
            f"(missing from manifest: {missing or 'none'}; not in header: {extra or 'none'})"
        )


def check_versions_and_counts(manifest: dict, rel: str, lines: list[str], problems: list[str]) -> None:
    version = core_version()
    core_count = sum(1 for a in manifest["algorithms"] if a["kind"] == "core")
    language_count = len({l["name"] for l in manifest["languages"]})
    upstream = upstream_library_count()
    number = "|".join(list(NUMBER_WORDS) + [r"\d+"])
    count_re = re.compile(
        rf"\b({number})\s+((?:battle-tested\s+)?(?:upstream\s+)?(?:compression\s+)?(?:algorithms|codecs|libraries))\b",
        re.IGNORECASE,
    )
    for i, line, in_fence, _ in iter_lines(lines):
        if REGION_RE.match(line):
            continue
        if re.search(r"[Vv]ersion\(\)", line):
            for lit in re.findall(r'"(\d+\.\d+\.\d+)"', line):
                if lit != version:
                    problems.append(f"{rel}:{i + 1}: version example \"{lit}\" != CMakeLists.txt DEFAULT_VERSION \"{version}\"")
        if in_fence:
            continue
        for m in count_re.finditer(line):
            word = m.group(1).lower()
            n = int(word) if word.isdigit() else NUMBER_WORDS[word]
            want = upstream if "upstream" in m.group(2).lower() or "librar" in m.group(2).lower() else core_count
            if n != want:
                problems.append(f"{rel}:{i + 1}: says \"{m.group(0)}\" but the source of truth has {want}")
        for kind, want in (("algorithms", core_count), ("languages", language_count)):
            for m in re.finditer(rf"badge/{kind}-(\d+)-", line):
                if int(m.group(1)) != want:
                    problems.append(f"{rel}:{i + 1}: {kind} badge says {m.group(1)}, manifest has {want}")


def check_sections(rel: str, key: str, lines: list[str], problems: list[str]) -> None:
    required = ROOT_SECTIONS if key == "root" else BINDING_SECTIONS
    if key == "c":
        return
    heads = [(i, text) for i, level, text in headings(lines) if level >= 2]
    pos = -1
    for name, pattern in required:
        hit = next((n for n, (i, text) in enumerate(heads) if re.search(pattern, text.strip().lower())), None)
        if hit is None:
            problems.append(f"{rel}: missing required section '{name}' (see docs/readme-skeleton.md)")
            continue
        if hit < pos:
            problems.append(f"{rel}:{heads[hit][0] + 1}: section '{name}' is out of order (see docs/readme-skeleton.md)")
        pos = max(pos, hit)


BLOCK_START = re.compile(r"^(#|\||<|>|```|~~~|!\[|\[!\[|---|===)")
LIST_ITEM = re.compile(r"^([-*+]|\d+[.)])\s")


def check_hard_wrap(rel: str, lines: list[str], problems: list[str]) -> None:
    in_region = False
    flagged = 0
    state = list(iter_lines(lines))
    for n, (i, line, in_fence, _) in enumerate(state):
        if REGION_RE.match(line):
            in_region = True
        elif END_RE.match(line):
            in_region = False
        if in_fence or in_region or n + 1 >= len(state):
            continue
        j, nxt, nxt_fence, _ = state[n + 1]
        cur, nx = line.strip(), nxt.strip()
        if not cur or not nx or nxt_fence or BLOCK_START.match(cur) or BLOCK_START.match(nx) or LIST_ITEM.match(nx):
            continue
        if line.endswith("  ") or line.endswith("\\") or cur.startswith("<!--"):
            continue
        flagged += 1
        if flagged <= 3:
            problems.append(f"{rel}:{i + 1}: prose is hard-wrapped; keep one paragraph or list item per line")
    if flagged > 3:
        problems.append(f"{rel}: ...and {flagged - 3} more hard-wrapped lines")


LINK_RE = re.compile(r"!?\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
SRC_RE = re.compile(r'(?:src|href)="([^"]+)"')


def check_links(rel: str, key: str, path: Path, lines: list[str], problems: list[str]) -> None:
    anchors = {slugify(text) for _, _, text in headings(lines)}
    for i, line, in_fence, _ in iter_lines(lines):
        if in_fence:
            continue
        for target in LINK_RE.findall(line) + SRC_RE.findall(line):
            if target.startswith("#"):
                if target[1:] not in anchors:
                    problems.append(f"{rel}:{i + 1}: anchor {target} matches no heading")
                continue
            blob = re.match(rf"^{re.escape(REPO_URL)}/(?:blob|tree)/main/([^#?]+)", target)
            if blob:
                if not (REPO_ROOT / blob.group(1)).exists():
                    problems.append(f"{rel}:{i + 1}: {target} points at a path that does not exist")
                continue
            if re.match(r"^[a-z][a-z0-9+.-]*:", target):
                continue
            if key in ABSOLUTE_LINKS_ONLY:
                problems.append(f"{rel}:{i + 1}: relative link '{target}'; this README renders on a registry, use an absolute {REPO_URL}/blob/main/... URL")
                continue
            if not (path.parent / target.split("#")[0]).exists():
                problems.append(f"{rel}:{i + 1}: link target '{target}' does not exist")


def check_rustdoc_lines(rel: str, lines: list[str], problems: list[str]) -> None:
    fence_lang = ""
    for i, line, in_fence, lang in iter_lines(lines):
        if in_fence and lang:
            fence_lang = lang
        if in_fence and fence_lang in ("rust", "rs") and re.match(r"^#( |$)", line):
            problems.append(f"{rel}:{i + 1}: rustdoc-hidden line '{line}' renders literally outside rustdoc")
        if not in_fence:
            fence_lang = ""


def check_metadata(problems: list[str]) -> None:
    found: dict[str, tuple[str | None, str | None]] = {}
    cargo = tomllib.loads((REPO_ROOT / "Cargo.toml").read_text(encoding="utf-8")).get("package", {})
    found["Cargo.toml"] = (cargo.get("license"), cargo.get("repository"))
    proj = tomllib.loads((REPO_ROOT / "bindings/python/pyproject.toml").read_text(encoding="utf-8")).get("project", {})
    lic = proj.get("license")
    found["bindings/python/pyproject.toml"] = (
        lic.get("text") if isinstance(lic, dict) else lic,
        proj.get("urls", {}).get("Repository"),
    )
    pkg = json.loads((REPO_ROOT / "bindings/wasm/package.json").read_text(encoding="utf-8"))
    repo = pkg.get("repository")
    repo = repo.get("url") if isinstance(repo, dict) else repo
    repo = re.sub(r"^git\+|\.git$", "", repo or "")
    found["bindings/wasm/package.json"] = (pkg.get("license"), repo)
    for path, (lic, repo) in found.items():
        if lic != "MIT":
            problems.append(f"{path}: license is {lic!r}, expected 'MIT'")
        if repo != REPO_URL:
            problems.append(f"{path}: repository is {repo!r}, expected {REPO_URL!r}")


# --------------------------------------------------------------------------- #


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--fix", action="store_true", help="regenerate the marked regions from the manifest")
    args = ap.parse_args()

    manifest = load_manifest()
    problems: list[str] = []
    check_enum(manifest, problems)
    check_metadata(problems)

    for key, rel in manifest["readmes"].items():
        path = REPO_ROOT / rel
        lines = path.read_text(encoding="utf-8").split("\n")
        new_lines = process_regions(manifest, key, lines, args.fix, problems, rel)
        if args.fix and new_lines != lines:
            path.write_text("\n".join(new_lines), encoding="utf-8")
            print(f"updated {rel}")
            problems = [p for p in problems if not (p.startswith(f"{rel}:") and "out of date" in p)]
            lines = new_lines
        check_versions_and_counts(manifest, rel, lines, problems)
        check_sections(rel, key, lines, problems)
        check_hard_wrap(rel, lines, problems)
        check_links(rel, key, path, lines, problems)
        check_rustdoc_lines(rel, lines, problems)

    for p in problems:
        print(p)
    if problems:
        print(f"\n{len(problems)} problem(s). Run `tools/check-readmes.py --fix` for generated regions; "
              f"see docs/readme-skeleton.md for the rest.", file=sys.stderr)
        return 1
    print("READMEs are aligned.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
